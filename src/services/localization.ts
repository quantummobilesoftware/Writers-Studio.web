export function getSystemLanguageCode(): string {
  if (typeof navigator !== 'undefined' && navigator.language) {
    return navigator.language.split('-')[0].toLowerCase();
  }
  return 'ru';
}

export function resolveEffectiveLanguage(pref: string): string {
  if (pref && pref !== 'system') return pref.toLowerCase();
  const sys = getSystemLanguageCode();
  if (SUPPORTED_LANGUAGES.some(l => l.code === sys && l.code !== 'system')) {
    return sys;
  }
  return 'ru';
}

export function isRussian(lang: string): boolean {
  const eff = resolveEffectiveLanguage(lang);
  return eff === 'ru' || eff === 'be' || eff === 'uk' || eff === 'kk';
}

